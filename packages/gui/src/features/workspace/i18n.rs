//! The one translation adapter of the workspace, schedules, logs and command-center
//! features.
//!
//! Catalog keys (`assets/locales/{en,ko}.json`, Flutter `tr(context, key, args)`) go to the
//! shell's common translation utility. English literals the Flutter app showed without a
//! catalog key (schedules, execution log toolbar, new-tab options, workspace recovery) are
//! translated here so Korean users get Korean text; unknown literals stay English.

/// Translates a catalog key.
pub fn t(key: &str) -> String {
    crate::common::tr(key)
}

/// Translates a catalog key with `{{name}}` interpolation.
pub fn ta(key: &str, args: &[(&str, &str)]) -> String {
    crate::common::tr_args(key, args)
}

/// Follows the shell's current language (`preferences.language`, system locale).
fn korean() -> bool {
    crate::common::locale_tag() == "ko"
}

/// Translates an English literal.
pub fn l(english: &'static str) -> &'static str {
    if !korean() {
        return english;
    }
    KO.iter().find(|(en, _)| *en == english).map(|(_, ko)| *ko).unwrap_or(english)
}

/// Translates an English literal and fills `{name}` placeholders.
pub fn lf(english: &'static str, args: &[(&str, &str)]) -> String {
    let mut text = l(english).to_owned();
    for (name, value) in args {
        text = text.replace(&format!("{{{name}}}"), value);
    }
    text
}

